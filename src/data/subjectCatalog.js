export const subjectCatalog = subjectDetails.map(([name, Icon, description, color]) => ({
  name,
  slug: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, ''),
  Icon,
  description,
  color,
  topics: (topicSets[name] || []).map(([topic, difficulty]) => ({
    name: topic,
    difficulty,
    quizCount: 12,
    points: '5-20',
  })),
}));

export const getSubject = (slug) => subjectCatalog.find((subject) => subject.slug === slug);
